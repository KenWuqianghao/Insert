/// Clipboard data as ordered `(MIME type, bytes)` entries. The platform reads a selection into
/// one of these, and storage keeps the payload of each clip as one of these.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct MimeMap(pub Vec<(String, Vec<u8>)>);

impl From<Vec<(String, Vec<u8>)>> for MimeMap {
    fn from(entries: Vec<(String, Vec<u8>)>) -> Self {
        Self(entries)
    }
}

impl MimeMap {
    pub fn get(&self, mime: &str) -> Option<&[u8]> {
        self.0.iter().find(|(name, _)| name == mime).map(|(_, data)| data.as_slice())
    }

    pub fn mimes(&self) -> impl Iterator<Item = &str> {
        self.0.iter().map(|(name, _)| name.as_str())
    }

    pub fn byte_count(&self) -> u64 {
        self.0.iter().map(|(_, data)| data.len() as u64).sum()
    }

    /// The text for "Paste as Plain Text": the text, else the file paths one per line, else the URL.
    pub fn plain_text(&self) -> Option<String> {
        if let Some(text) = self.get(UTF8_TEXT).and_then(|data| std::str::from_utf8(data).ok()) {
            return Some(text.to_owned());
        }
        let files = self.file_uris();
        if !files.is_empty() {
            return Some(files.iter().map(|uri| crate::model::file_path(uri)).collect::<Vec<_>>().join("\n"));
        }
        self.url_and_title().map(|(url, _)| url)
    }

    /// A clipboard offer that holds only `text`.
    pub fn from_plain_text(text: &str) -> Self {
        Self(vec![(UTF8_TEXT.to_owned(), text.as_bytes().to_vec())]).for_clipboard()
    }

    /// The entries to offer when Insert writes this payload to the clipboard. Storage keeps one
    /// UTF-8 text entry. Older apps ask for the other text names.
    pub fn for_clipboard(&self) -> Self {
        let mut offer = self.0.clone();
        if let Some(text) = self.get(UTF8_TEXT) {
            for alias in TEXT_ALIASES {
                if self.get(alias).is_none() {
                    offer.push((alias.to_owned(), text.to_vec()));
                }
            }
        }
        Self(offer)
    }

    pub(crate) fn file_uris(&self) -> Vec<String> {
        let from_list: Vec<String> = self.get(URI_LIST).map(uri_lines).unwrap_or_default();
        let files: Vec<String> = from_list.into_iter().filter(|uri| is_file_uri(uri)).collect();
        if !files.is_empty() {
            return files;
        }
        self.get(GNOME_COPIED_FILES)
            .map(|data| uri_lines(data).into_iter().skip(1).filter(|uri| is_file_uri(uri)).collect())
            .unwrap_or_default()
    }

    pub(crate) fn url_and_title(&self) -> Option<(String, Option<String>)> {
        let lines = |text: String| {
            let mut lines = text.lines().map(str::trim).map(str::to_owned).collect::<Vec<_>>().into_iter();
            let url = lines.next()?;
            let title = lines.next().filter(|title| !title.is_empty());
            Some((url, title))
        };
        let candidate = self
            .get(MOZ_URL)
            .map(decode_moz_url)
            .and_then(lines)
            .or_else(|| self.get(NETSCAPE_URL).map(|d| String::from_utf8_lossy(d).into_owned()).and_then(lines))
            .or_else(|| {
                let uris = self.get(URI_LIST).map(uri_lines).unwrap_or_default();
                uris.into_iter().find(|uri| !is_file_uri(uri)).map(|uri| (uri, None))
            })?;
        url::Url::parse(&candidate.0).ok().map(|_| candidate)
    }

    pub(crate) fn image(&self) -> Option<&[u8]> {
        self.0.iter().filter(|(name, _)| image_rank(name).is_some()).min_by_key(|(name, _)| image_rank(name)).map(|(_, d)| d.as_slice())
    }
}

/// The MIME name storage uses for text. Every UTF-8 text target is stored under this name.
pub const UTF8_TEXT: &str = "text/plain;charset=utf-8";
const TEXT_ALIASES: [&str; 2] = ["text/plain", "UTF8_STRING"];

pub(crate) const HTML: &str = "text/html";
pub(crate) const URI_LIST: &str = "text/uri-list";
pub(crate) const GNOME_COPIED_FILES: &str = "x-special/gnome-copied-files";
pub(crate) const MOZ_URL: &str = "text/x-moz-url";
pub(crate) const NETSCAPE_URL: &str = "_NETSCAPE_URL";
pub(crate) const PDF: &str = "application/pdf";
pub(crate) const COLOR: &str = "application/x-color";
pub(crate) const KDE_PASSWORD_HINT: &str = "x-kde-passwordManagerHint";

const RICH_TEXT: [&str; 3] = ["text/rtf", "application/rtf", "text/richtext"];
const OTHER_STORED: [&str; 9] = [
    HTML,
    URI_LIST,
    GNOME_COPIED_FILES,
    MOZ_URL,
    NETSCAPE_URL,
    PDF,
    COLOR,
    "text/tab-separated-values",
    "image/svg+xml",
];
const PRIVACY_MARKERS: [&str; 3] = [
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.TransientType",
    "org.nspasteboard.AutoGeneratedType",
];
const VOLATILE: [&str; 1] = ["chromium/x-web-custom-data"];
const PREFERRED_IMAGES: [&str; 6] = ["image/png", "image/jpeg", "image/webp", "image/gif", "image/tiff", "image/bmp"];

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) enum TextEncoding {
    Utf8,
    Latin1,
}

/// Text targets in order of preference. `STRING` is Latin-1 by the X11 rules.
pub(crate) fn text_source(mime: &str) -> Option<(usize, TextEncoding)> {
    let normalized: String = mime.chars().filter(|c| !c.is_whitespace()).collect::<String>().to_ascii_lowercase();
    match normalized.as_str() {
        "text/plain;charset=utf-8" => Some((0, TextEncoding::Utf8)),
        _ if mime == "UTF8_STRING" => Some((1, TextEncoding::Utf8)),
        "text/plain" => Some((2, TextEncoding::Utf8)),
        _ if mime == "STRING" => Some((3, TextEncoding::Latin1)),
        _ => None,
    }
}

/// Lower is better. SVG is stored, but it is not an image kind.
pub(crate) fn image_rank(mime: &str) -> Option<usize> {
    if mime == "image/svg+xml" || !mime.starts_with("image/") {
        return None;
    }
    Some(PREFERRED_IMAGES.iter().position(|preferred| *preferred == mime).unwrap_or(PREFERRED_IMAGES.len()))
}

pub(crate) fn is_rich_text(mime: &str) -> bool {
    RICH_TEXT.contains(&mime)
}

pub(crate) fn is_media(mime: &str) -> bool {
    mime.starts_with("audio/") || mime.starts_with("video/")
}

pub(crate) fn is_volatile(mime: &str) -> bool {
    VOLATILE.contains(&mime)
}

pub(crate) fn is_privacy_marker(mime: &str) -> bool {
    PRIVACY_MARKERS.contains(&mime)
}

/// Stored as is. Text and images go through a separate pick.
pub(crate) fn is_plain_stored(mime: &str) -> bool {
    is_rich_text(mime) || OTHER_STORED.contains(&mime) || is_media(mime) || is_volatile(mime)
}

/// The offered targets worth reading for capture: privacy markers, every text target, the best
/// image target, and the stored types. The platform can skip all other targets.
pub fn select_targets(offered: &[String]) -> Vec<String> {
    let best_image = offered.iter().filter_map(|mime| image_rank(mime).map(|rank| (rank, mime))).min().map(|(_, mime)| mime);
    offered
        .iter()
        .filter(|mime| {
            is_privacy_marker(mime)
                || mime.as_str() == KDE_PASSWORD_HINT
                || text_source(mime).is_some()
                || is_plain_stored(mime)
                || Some(*mime) == best_image
        })
        .cloned()
        .collect()
}

fn uri_lines(data: &[u8]) -> Vec<String> {
    String::from_utf8_lossy(data)
        .lines()
        .map(str::trim)
        .filter(|line| !line.is_empty() && !line.starts_with('#'))
        .map(str::to_owned)
        .collect()
}

fn is_file_uri(uri: &str) -> bool {
    url::Url::parse(uri).is_ok_and(|url| url.scheme() == "file")
}

/// Firefox writes `text/x-moz-url` as UTF-16 in host byte order.
fn decode_moz_url(data: &[u8]) -> String {
    let looks_utf16 = data.len() % 2 == 0 && data.iter().skip(1).step_by(2).any(|byte| *byte == 0);
    if !looks_utf16 {
        return String::from_utf8_lossy(data).into_owned();
    }
    let units: Vec<u16> = data.chunks_exact(2).map(|pair| u16::from_le_bytes([pair[0], pair[1]])).collect();
    String::from_utf16_lossy(&units).trim_start_matches('\u{FEFF}').trim_end_matches('\0').to_owned()
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(mime: &str, data: &[u8]) -> (String, Vec<u8>) {
        (mime.to_owned(), data.to_vec())
    }

    #[test]
    fn select_targets_keeps_one_image_and_drops_unknown_targets() {
        let offered: Vec<String> = ["TARGETS", "TIMESTAMP", "image/bmp", "image/png", "image/jpeg", "application/x-qt-image", "UTF8_STRING", "x-kde-passwordManagerHint"]
            .map(str::to_owned)
            .to_vec();
        assert_eq!(select_targets(&offered), ["image/png", "UTF8_STRING", "x-kde-passwordManagerHint"]);
    }

    #[test]
    fn plain_text_falls_back_to_file_paths_then_url() {
        let text = MimeMap(vec![entry(UTF8_TEXT, b"hi")]);
        assert_eq!(text.plain_text().as_deref(), Some("hi"));
        let files = MimeMap(vec![entry(URI_LIST, b"file:///a/b.txt\r\nfile:///c%20d\r\n")]);
        assert_eq!(files.plain_text().as_deref(), Some("/a/b.txt\n/c d"));
        let url = MimeMap(vec![entry(NETSCAPE_URL, b"https://example.com\nExample")]);
        assert_eq!(url.plain_text().as_deref(), Some("https://example.com"));
    }

    #[test]
    fn for_clipboard_adds_text_aliases() {
        let offer = MimeMap::from_plain_text("hi");
        let mimes: Vec<&str> = offer.mimes().collect();
        assert_eq!(mimes, [UTF8_TEXT, "text/plain", "UTF8_STRING"]);
        assert!(offer.0.iter().all(|(_, data)| data == b"hi"));
    }
}
